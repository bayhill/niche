import CoreGraphics
import Foundation
import ImageIO
import NotchCore

/// Size and count limits. History lives in memory only.
public struct ClipboardLimits: Sendable, Equatable {
    public var maxTextBytes = 100_000
    public var maxImageBytes = 20_000_000
    /// Entries of any kind (the "history size").
    public var maxEntries = 50
    /// Of those, at most this many images.
    public var maxImageEntries = 20

    public init() {}

    /// The limits for a "history size" setting. Images may take up to 40% of it: 10 → 4, 25 → 10, 50 → 20.
    public init(historySize: Int) {
        let size = min(50, max(1, historySize))
        maxEntries = size
        maxImageEntries = max(1, min(20, Int((Double(size) * 0.4).rounded())))
    }
}

/// One remembered copy.
public struct ClipboardEntry: Identifiable, Sendable, Equatable {
    public let id: UUID
    public let content: ClipboardContent
    public let copiedAt: Date
    /// Text: the start of the text with runs of whitespace collapsed, for the tile.
    public let preview: String
    /// Image: pixel dimensions, when ImageIO can read them.
    public let pixelSize: CGSize?
    public let kind: ClipKind
    /// Display name of the app that was frontmost when this was copied, when known.
    public let sourceApp: String?

    public init(id: UUID = UUID(), content: ClipboardContent, copiedAt: Date, sourceApp: String? = nil) {
        self.id = id
        self.content = content
        self.copiedAt = copiedAt
        self.sourceApp = sourceApp
        switch content {
        case .text(let text):
            preview = Self.preview(of: text)
            pixelSize = nil
            kind = ClipKind.detect(text)
        case .image(let data, _):
            preview = ""
            pixelSize = ClipboardImages.pixelSize(of: data)
            kind = .image
        }
    }

    public var isImage: Bool { if case .image = content { true } else { false } }

    static func preview(of text: String) -> String {
        text.prefix(600).split(whereSeparator: \.isWhitespace).joined(separator: " ")
    }
}

/// The history, newest first. A pure value type so the rules are testable without a pasteboard.
public struct ClipboardHistory: Sendable, Equatable {
    public private(set) var entries: [ClipboardEntry] = []
    public var limits: ClipboardLimits {
        didSet { trim() }
    }

    public init(limits: ClipboardLimits = ClipboardLimits(), entries: [ClipboardEntry] = []) {
        self.limits = limits
        self.entries = entries
        trim()
    }

    /// Adds `entry` at the front. A copy identical to the newest entry is ignored. Returns whether it was added.
    @discardableResult
    public mutating func record(_ entry: ClipboardEntry) -> Bool {
        if let newest = entries.first, newest.content == entry.content { return false }
        entries.insert(entry, at: 0)
        trim()
        return true
    }

    /// Moves an entry to the front (it was just copied again).
    public mutating func promote(_ id: ClipboardEntry.ID) {
        guard let index = entries.firstIndex(where: { $0.id == id }), index > 0 else { return }
        entries.insert(entries.remove(at: index), at: 0)
    }

    public mutating func remove(_ id: ClipboardEntry.ID) { entries.removeAll { $0.id == id } }
    public mutating func clear() { entries.removeAll() }

    /// Drops the oldest images past the image cap, then the oldest entries past the total cap.
    private mutating func trim() {
        var images = 0
        entries = entries.filter { entry in
            guard entry.isImage else { return true }
            images += 1
            return images <= limits.maxImageEntries
        }
        if entries.count > limits.maxEntries { entries.removeLast(entries.count - limits.maxEntries) }
    }
}

/// Why a copy was not recorded.
public enum ClipboardSkip: Sendable, Equatable {
    /// Marked by the source app as private or temporary (password managers do this).
    case markedPrivate(type: String)
    /// Copied while a password manager was the frontmost app.
    case passwordManager(bundleID: String)
    /// Colours, files with no shelf to take them, or anything else that is not text or an image.
    case unsupported
    case empty
    case tooLarge
}

/// The rules for what gets remembered. Pure: no pasteboard of its own.
public enum ClipboardPolicy {
    /// Marker types from nspasteboard.org and password managers. A copy carrying any of them is never read.
    public static let privateMarkerTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Copies made while one of these apps is frontmost are ignored.
    public static let passwordManagerBundleIDs: Set<String> = [
        "com.1password.1password",          // 1Password 8
        "com.agilebits.onepassword7",       // 1Password 7
        "com.agilebits.onepassword-osx",    // 1Password 6
        "com.bitwarden.desktop",            // Bitwarden
        "com.apple.Passwords",              // Apple Passwords
        "com.apple.keychainaccess",         // Keychain Access
    ]

    public enum Outcome: Sendable, Equatable {
        case record(ClipboardContent)
        /// Files copied in Finder: they belong on the Shelf, not in the history.
        case files([URL])
        case skip(ClipboardSkip)
    }

    /// Decides what to do with the pasteboard's current contents, reading as little as possible:
    /// nothing at all for a password manager, only the type list for marked or unsupported copies.
    @MainActor
    public static func evaluate(_ pasteboard: some PasteboardAccessing, frontmostBundleID: String?, limits: ClipboardLimits) -> Outcome {
        if let app = frontmostBundleID, passwordManagerBundleIDs.contains(app) { return .skip(.passwordManager(bundleID: app)) }

        let types = pasteboard.types()
        if let marker = types.first(where: privateMarkerTypes.contains) { return .skip(.markedPrivate(type: marker)) }
        if types.contains(PasteboardTypes.fileURL) {
            let urls = pasteboard.fileURLs()
            return urls.isEmpty ? .skip(.unsupported) : .files(urls)
        }

        let imageType = PasteboardTypes.images.first(where: types.contains)
        let hasText = types.contains(PasteboardTypes.plainText)
        guard hasText || imageType != nil else { return .skip(.unsupported) }

        let text = hasText ? pasteboard.string() : nil
        // Text wins, except a bare link that came along with an image ("Copy Image" in a browser).
        if let text, imageType == nil || !looksLikeLink(text) {
            if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .skip(.empty) }
            if text.utf8.count > limits.maxTextBytes { return .skip(.tooLarge) }
            return .record(.text(text))
        }
        guard let imageType, let data = pasteboard.data(forType: imageType) else { return .skip(.unsupported) }
        if data.isEmpty { return .skip(.empty) }
        if data.count > limits.maxImageBytes { return .skip(.tooLarge) }
        return .record(.image(data, type: imageType))
    }

    static func looksLikeLink(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed), let scheme = url.scheme else { return false }
        return ["http", "https", "file", "data"].contains(scheme.lowercased())
    }
}

/// ImageIO helpers for copied image bytes. Nonisolated and cheap to call off the main actor.
public enum ClipboardImages {
    public static func pixelSize(of data: Data) -> CGSize? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let w = props[kCGImagePropertyPixelWidth] as? Int, let h = props[kCGImagePropertyPixelHeight] as? Int
        else { return nil }
        let orientation = props[kCGImagePropertyOrientation] as? Int ?? 1
        return orientation >= 5 ? CGSize(width: h, height: w) : CGSize(width: w, height: h)
    }

    /// A downscaled, orientation-corrected thumbnail.
    public static func thumbnail(of data: Data, maxPixels: Int) -> SendableImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixels,
        ]
        return CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary).map(SendableImage.init)
    }

    /// File-type extension for a pasteboard image type.
    static func fileExtension(for type: String) -> String {
        switch type {
        case "public.png": "png"
        case "public.jpeg": "jpg"
        case "public.heic": "heic"
        case "org.webmproject.webp": "webp"
        case "com.compuserve.gif": "gif"
        default: "tiff"
        }
    }
}
