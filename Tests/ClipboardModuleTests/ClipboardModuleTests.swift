        defer { named.releaseGlobally() }
        #expect(named.name != .general)
        let adapter = SystemPasteboard(named)
        #expect(adapter.access == .allowed)  // only the general pasteboard asks

        named.clearContents()
        named.declareTypes([.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")], owner: nil)
        named.setString("hunter2", forType: .string)
        named.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        #expect(ClipboardPolicy.evaluate(adapter, frontmostBundleID: nil, limits: ClipboardLimits()) == .skip(.markedPrivate(type: "org.nspasteboard.ConcealedType")))

        let before = adapter.changeCount
        let after = adapter.write(.text("hello"))
        #expect(after != before)
        #expect(after == named.changeCount)
        #expect(adapter.string() == "hello")
        #expect(ClipboardPolicy.evaluate(adapter, frontmostBundleID: nil, limits: ClipboardLimits()) == .record(.text("hello")))

        adapter.write(.image(png, type: "public.png"))
        #expect(adapter.data(forType: "public.png") == png)

        let file = URL(fileURLWithPath: "/tmp/niche-test-file.txt")
        named.clearContents()
        named.writeObjects([file as NSURL])
        #expect(adapter.fileURLs() == [file])
        #expect(ClipboardPolicy.evaluate(adapter, frontmostBundleID: nil, limits: ClipboardLimits()) == .skip(.files))
        #expect(ClipboardPolicy.evaluate(adapter, frontmostBundleID: nil, limits: ClipboardLimits(), acceptFiles: true) == .files([file]))
    }
