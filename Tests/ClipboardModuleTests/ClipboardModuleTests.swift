        #expect(h.module.lastSkip == .passwordManager(bundleID: bundleID))
        #expect(h.pasteboard.contentReads == 0)

        h.frontmost.bundleID = "com.apple.TextEdit"
        h.pasteboard.copy(text: "ordinary")
