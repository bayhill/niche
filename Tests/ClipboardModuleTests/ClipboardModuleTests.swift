    }

    @Test func textCap() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        h.pasteboard.copy(text: String(repeating: "a", count: 100_001))
        h.module.poll()
        #expect(h.module.lastSkip == .tooLarge)
        #expect(h.module.entries.isEmpty)
        h.pasteboard.copy(text: String(repeating: "é", count: 50_000))  // exactly 100 000 UTF-8 bytes
        h.module.poll()
        #expect(h.module.entries.count == 1)
    }

    @Test func imageCap() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        h.pasteboard.copy(image: Data(count: 20_000_001))
        h.module.poll()
        #expect(h.module.lastSkip == .tooLarge)
        h.pasteboard.copy(image: Data(count: 20_000_000))
        h.module.poll()
        #expect(h.module.entries.count == 1)
    }

    @Test func entryCaps() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        for i in 0..<25 {
            h.pasteboard.copy(image: png + Data([UInt8(i)]))
            h.module.poll()
        }
        for i in 0..<55 {
            h.pasteboard.copy(text: "text \(i)")
            h.module.poll()
        }
        #expect(h.module.entries.filter(\.isImage).count == 20)
        #expect(h.texts().count == 50)
        #expect(h.texts().first == "text 54")
        #expect(h.texts().last == "text 5")
        // The newest images survived.
        #expect(h.module.entries.filter(\.isImage).first?.content == .image(png + Data([24]), type: "public.png"))
    }

    @Test func historySizeSettingShrinksTheCaps() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        for i in 0..<30 {
            h.pasteboard.copy(text: "t\(i)")
            h.module.poll()
        }
        h.module.setHistorySize(10)
        #expect(h.texts().count == 10)
        #expect(h.env.settings.get(ClipboardModule.historySizeKey) == 10)
        #expect(ClipboardLimits(historySize: 10).maxImageEntries == 4)
        #expect(ClipboardLimits(historySize: 25).maxImageEntries == 10)
        #expect(ClipboardLimits(historySize: 50) == ClipboardLimits())
    }

    @Test func consecutiveDuplicatesAreDropped() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        for text in ["a", "a", "b", "a", "a"] {
            h.pasteboard.copy(text: text)
            h.module.poll()
        }
        #expect(h.texts() == ["a", "b", "a"])
        h.pasteboard.copy(image: png)
        h.module.poll()
        h.pasteboard.copy(image: png)
        h.module.poll()
        #expect(h.module.entries.filter(\.isImage).count == 1)
    }

    @Test func copyingBackIsNotRecordedAgainAndMovesToFront() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        for text in ["one", "two", "three"] {
            h.pasteboard.copy(text: text)
            h.module.poll()
        }
        let one = try #require(h.module.entries.last)
        h.module.copy(one)
        #expect(h.pasteboard.writes == [.text("one")])
        #expect(h.module.confirmedID == one.id)
        h.module.poll()
        #expect(h.texts() == ["one", "three", "two"])
        #expect(h.module.entries.count == 3)

        // Another app copying the same text afterwards is a real change but a consecutive duplicate.
        h.pasteboard.copy(text: "one")
        h.module.poll()
        #expect(h.module.entries.count == 3)
        h.pasteboard.copy(text: "four")
        h.module.poll()
        #expect(h.texts() == ["four", "one", "three", "two"])
    }

    @Test func textWinsOverImageUnlessItIsJustALink() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        h.pasteboard.setContents([(PasteboardTypes.plainText, Data("A paragraph".utf8)), ("public.png", png)])
        h.module.poll()
        #expect(h.texts() == ["A paragraph"])
        h.pasteboard.setContents([(PasteboardTypes.plainText, Data("https://example.com/cat.png".utf8)), ("public.tiff", png)])
        h.module.poll()
        #expect(h.module.entries.first?.content == .image(png, type: "public.tiff"))
    }

    @Test func convertSendsImageDataToTheConverter() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        h.pasteboard.copy(image: png)
        h.module.poll()
        h.pasteboard.copy(text: "not an image")
        h.module.poll()
        #expect(h.module.canConvert)
        let image = try #require(h.module.entries.first(where: { $0.isImage }))
        h.module.convert(image)
        h.module.convert(h.module.entries[0])  // text: ignored
        #expect(h.env.converter.requests.count == 1)
        let source = try #require(h.env.converter.requests.first?.first)
        guard case .imageData(let data, let name) = source else { Issue.record("expected image data"); return }
        #expect(data == png)
        #expect(name.hasPrefix("Clipboard "))
        #expect(ClipboardModule.conversionName(for: Date(timeIntervalSince1970: 0)).hasPrefix("Clipboard 1970-01-01 at "))

        h.env.services.converter = nil
        #expect(!h.module.canConvert)
    }

    @Test func clearAndTurnOffForgetEverything() async throws {
        let h = try Harness(pollInterval: .milliseconds(10)); defer { h.finish() }
        await h.startMonitoring()
        h.pasteboard.copy(text: "x")
        h.module.poll()
