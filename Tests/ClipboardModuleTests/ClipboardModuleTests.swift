import Testing
@testable import ClipboardModule

@MainActor
private final class Frontmost { var bundleID: String? }

@MainActor
private struct Harness {
    let env: TestEnvironment
    let pasteboard: InMemoryPasteboard
    let frontmost = Frontmost()
    let module: ClipboardModule

    init(access: PasteboardAccess = .allowed, pollInterval: Duration = .seconds(3600)) throws {
        env = try TestEnvironment()
        pasteboard = InMemoryPasteboard(access: access)
        let frontmost = self.frontmost
        module = ClipboardModule(
            pasteboard: pasteboard, frontmostBundleID: { frontmost.bundleID }, pollInterval: pollInterval,
            openPrivacySettings: {}
        )
    }

    func start(mayPrompt: Bool = false) async { await module.start(env.context(for: .clipboard, mayPrompt: mayPrompt)) }

    /// Starts and turns monitoring on, as the user's click would.
    func startMonitoring() async {
        await start()
        module.turnOn()
    }

    func texts() -> [String] {
        module.entries.compactMap { if case .text(let t) = $0.content { t } else { nil } }
    }

    func finish() { module.stop(); env.cleanUp() }
}

private let png = TestImage.data(TestImage.solid(width: 4, height: 3))

@MainActor @Suite struct ClipboardMonitoringTests {
    @Test func basics() throws {
        let h = try Harness(); defer { h.finish() }
        #expect(h.module.id == .clipboard)
        #expect(h.module.placement == .page(order: 20))
        #expect(h.module.liveActivity == nil)
        #expect(h.module.requirements.count == 1)
        #expect(h.module.requirements[0].kind == .pasteboard && h.module.requirements[0].optional)
        #expect(h.module.settingsView() == nil)  // no settings store before start
    }

    @Test func offByDefaultAndNeverReadsThePasteboard() async throws {
        let h = try Harness(pollInterval: .milliseconds(10)); defer { h.finish() }
        await h.start(mayPrompt: true)
        #expect(h.env.settings.get(ClipboardModule.enabledKey) == false)
        #expect(h.module.status == .off)
        h.pasteboard.copy(text: "hello")
        h.module.poll()
        try await Task.sleep(for: .milliseconds(100))
        #expect(h.pasteboard.reads == 0)
        #expect(h.module.entries.isEmpty)
    }

    @Test func turningOnRecordsNewCopiesButNotWhatWasThereBefore() async throws {
        let h = try Harness(); defer { h.finish() }
        h.pasteboard.copy(text: "copied before consent")
        await h.startMonitoring()
        #expect(h.module.status == .monitoring)
        #expect(h.env.settings.get(ClipboardModule.enabledKey))
        h.module.poll()
        #expect(h.module.entries.isEmpty)
        #expect(h.pasteboard.contentReads == 0)

        h.pasteboard.copy(text: "first")
        h.module.poll()
        h.pasteboard.copy(image: png)
        h.module.poll()
        h.pasteboard.copy(text: "third")
        h.module.poll()
        #expect(h.module.entries.count == 3)
        #expect(h.texts() == ["third", "first"])
        #expect(h.module.entries[1].isImage)
        #expect(h.module.entries[1].pixelSize == CGSize(width: 4, height: 3))
    }

    @Test func readsOnlyWhenTheChangeCountMoves() async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        h.pasteboard.copy(text: "a")
        h.module.poll()
        let reads = h.pasteboard.contentReads
        for _ in 0..<5 { h.module.poll() }
        #expect(h.pasteboard.contentReads == reads)
    }

    @Test func timerPolls() async throws {
        let h = try Harness(pollInterval: .milliseconds(20)); defer { h.finish() }
        await h.startMonitoring()
        h.pasteboard.copy(text: "via timer")
        for _ in 0..<100 where h.module.entries.isEmpty { try await Task.sleep(for: .milliseconds(20)) }
        #expect(h.texts() == ["via timer"])
    }

    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"])
    func privateMarkersAreSkippedWithoutReadingContents(marker: String) async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        h.pasteboard.copy(text: "hunter2", markers: [marker])
        h.module.poll()
        #expect(h.module.entries.isEmpty)
        #expect(h.module.lastSkip == .markedPrivate(type: marker))
        #expect(h.pasteboard.contentReads == 1)  // the type list only

        h.pasteboard.copy(image: png, markers: [marker])
        h.module.poll()
