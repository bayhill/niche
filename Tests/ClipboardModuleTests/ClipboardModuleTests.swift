    }

    @Test(arguments: ClipboardPolicy.passwordManagerBundleIDs.sorted())
    func copiesFromPasswordManagersAreSkipped(bundleID: String) async throws {
        let h = try Harness(); defer { h.finish() }
        await h.startMonitoring()
        h.frontmost.bundleID = bundleID
        h.pasteboard.copy(text: "correct horse battery staple")
        h.module.poll()
