@Suite struct ClipboardHistoryTests {
    @Test func previewCollapsesWhitespace() {
        let entry = ClipboardEntry(content: .text("  func   main() {\n\n\tprint(1)\n}  "), copiedAt: .now)
        #expect(entry.preview == "func main() { print(1) }")
    }

    @Test func linkDetection() {
        #expect(ClipboardPolicy.looksLikeLink("https://apple.com/x"))
        #expect(!ClipboardPolicy.looksLikeLink("see https://apple.com"))
        #expect(!ClipboardPolicy.looksLikeLink("hello"))
    }

    @Test func promoteAndRemove() {
        var history = ClipboardHistory()
        let a = ClipboardEntry(content: .text("a"), copiedAt: .now)
        let b = ClipboardEntry(content: .text("b"), copiedAt: .now)
        history.record(a)
        history.record(b)
        history.promote(a.id)
        #expect(history.entries.map(\.id) == [a.id, b.id])
        history.remove(a.id)
        #expect(history.entries.map(\.id) == [b.id])
    }
}

/// The real `NSPasteboard` adapter, exercised on a private, uniquely named pasteboard (never the general one).
@MainActor @Suite struct SystemPasteboardTests {
    @Test func adapterReadsTypesSkipsMarkersAndWrites() throws {
        let named = NSPasteboard(name: NSPasteboard.Name("dev.bayhill.notcher.tests.\(UUID().uuidString)"))
        defer { named.releaseGlobally() }
        #expect(named.name != .general)
        let adapter = SystemPasteboard(named)
        #expect(adapter.access == .allowed)  // only the general pasteboard asks

        named.clearContents()
        named.declareTypes([.string, NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")], owner: nil)
        named.setString("hunter2", forType: .string)
        named.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        #expect(ClipboardPolicy.evaluate(adapter, frontmostBundleID: nil, limits: ClipboardLimits()) == .skip(.markedPrivate(type: "org.nspasteboard.ConcealedType")))

        let before = adapter.changeCount
        let after = adapter.write(.text("hello"))
        #expect(after != before)
        #expect(after == named.changeCount)
        #expect(adapter.string() == "hello")
        #expect(ClipboardPolicy.evaluate(adapter, frontmostBundleID: nil, limits: ClipboardLimits()) == .record(.text("hello")))

        adapter.write(.image(png, type: "public.png"))
        #expect(adapter.data(forType: "public.png") == png)
    }
}

@MainActor @Suite struct ClipboardSnapshotTests {
    @Test func snapshots() async throws {
        let env = try TestEnvironment(); defer { env.cleanUp() }
        let dir = ProcessInfo.processInfo.environment["NOTCHER_SNAPSHOT_DIR"].map { URL(fileURLWithPath: $0) } ?? env.root

        let sample = ClipboardModule.sample()
        await sample.start(env.context(for: .clipboard))
        try ViewSnapshot.write(module: sample, to: dir.appending(path: "clipboard-module.png"))
        // The scroll view does not render off-screen, so the row is also drawn without one.
        try ViewSnapshot.write(ClipboardPage(module: sample, scrolls: false), size: PanelLayout.pageSize, to: dir.appending(path: "clipboard.png"))

        let off = ClipboardModule(pasteboard: InMemoryPasteboard(), openPrivacySettings: {})
        try ViewSnapshot.write(module: off, to: dir.appending(path: "clipboard-off.png"))

        let denied = ClipboardModule(pasteboard: InMemoryPasteboard(access: .denied), openPrivacySettings: {})
        await denied.start(env.context(for: .clipboard))
        denied.turnOn()
        try ViewSnapshot.write(module: denied, to: dir.appending(path: "clipboard-denied.png"))
        #expect(FileManager.default.fileExists(atPath: dir.appending(path: "clipboard.png").path))
        denied.stop()
        sample.stop()
    }
}
